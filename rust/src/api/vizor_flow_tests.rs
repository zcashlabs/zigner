fn synthetic_note(
    fvk: &FullViewingKey,
    index: u8,
    version: NoteVersion,
    value: u64,
) -> orchard::Note {
    let rho = Rho::from_bytes(&[index; 32]).unwrap();
    let rseed = RandomSeed::from_bytes([42 + index; 32], &rho).unwrap();
    orchard::Note::from_parts(
        fvk.address_at(0u32, Scope::External),
        NoteValue::from_raw(value),
        rho,
        rseed,
        version,
    )
    .unwrap()
}

fn validate_builder_bundle(bundle: &orchard::pczt::Bundle) {
    bundle.verify_cross_address_restriction().unwrap();
    for action in bundle.actions() {
        action.verify_cv_net().unwrap();
        action.spend().verify_nullifier(None).unwrap();
        action.spend().verify_rk(None).unwrap();
        action
            .output()
            .verify_note_commitment(action.spend())
            .unwrap();
    }
}

fn build_pczt(index: u8) -> Pczt {
    let usk = seed_account();
    let fvk = FullViewingKey::from(usk.orchard());
    let recipient_key = orchard::keys::SpendingKey::from_bytes([90 + index; 32]).unwrap();
    let recipient_fvk = FullViewingKey::from(&recipient_key);
    let recipient = recipient_fvk.address_at(0u32, Scope::External);
    let mut builder = DeferredPcztBuilder::new::<zip317::FeeRule>(
        Network::TestNetwork,
        10_000_000u32.into(),
        BundlePadding::DEFAULT,
        BundlePadding::DEFAULT,
    )
    .unwrap();
    let (input_value, output_value) = if index == 0 {
        (1_000_000, 980_000)
    } else {
        (2_000_000, 1_990_000)
    };
    if index == 0 {
        builder
            .add_orchard_spend::<zip317::FeeRule>(
                fvk.clone(),
                synthetic_note(&fvk, index, NoteVersion::V2, input_value),
            )
            .unwrap();
    } else {
        builder
            .add_ironwood_spend::<zip317::FeeRule>(
                fvk.clone(),
                synthetic_note(&fvk, index, NoteVersion::V3, input_value),
            )
            .unwrap();
    }
    builder
        .add_ironwood_output::<zip317::FeeRule>(
            Some(fvk.to_ovk(Scope::External)),
            recipient,
            Zatoshis::const_from_u64(output_value),
            MemoBytes::empty(),
        )
        .unwrap();
    // Deterministic RNG also covers padding signatures.
    let mut rng = StdRng::from_seed([11 + index; 32]);
    let pczt = Creator::build_from_parts(
        builder
            .build_for_pczt(&mut rng, &zip317::FeeRule::standard())
            .unwrap()
            .pczt_parts,
    )
    .unwrap();
    // Validate before the signer drops full viewing keys.
    let pczt = Verifier::new(pczt)
        .with_orchard::<(), _>(|bundle| {
            validate_builder_bundle(bundle);
            Ok(())
        })
        .unwrap()
        .with_ironwood::<(), _>(|bundle| {
            validate_builder_bundle(bundle);
            Ok(())
        })
        .unwrap()
        .finish();
    let sighash = Signer::new(pczt.clone()).unwrap().shielded_sighash();
    let has_orchard = !pczt.orchard().actions().is_empty();
    let mut signer = LowLevelSigner::new(pczt);
    if has_orchard {
        signer = signer
            .sign_orchard_with::<OrchardParseError, _>(|_, bundle, flags| {
                bundle.finalize_io(sighash, &mut rng).unwrap();
                *flags &= !0x83;
                Ok(())
            })
            .unwrap();
    }
    signer = signer
        .sign_ironwood_with::<OrchardParseError, _>(|_, bundle, flags| {
            bundle.finalize_io(sighash, &mut rng).unwrap();
            *flags &= !0x83;
            Ok(())
        })
        .unwrap();
    let pczt = signer.finish();
    let updater = Updater::new(pczt)
        .update_orchard_with(|mut updater| {
            let addresses: Vec<_> = updater
                .bundle()
                .actions()
                .iter()
                .map(|a| {
                    UnifiedAddress::from_receivers(*a.output().recipient(), None)
                        .unwrap()
                        .encode(&Network::TestNetwork)
                })
                .collect();
            for (index, address) in addresses.into_iter().enumerate() {
                updater.update_action_with(index, |mut a| {
                    a.set_output_user_address(address);
                    Ok(())
                })?;
            }
            Ok(())
        })
        .unwrap()
        .update_ironwood_with(|mut updater| {
            let addresses: Vec<_> = updater
                .bundle()
                .actions()
                .iter()
                .map(|a| {
                    UnifiedAddress::from_receivers(*a.output().recipient(), None)
                        .unwrap()
                        .encode(&Network::TestNetwork)
                })
                .collect();
            for (index, address) in addresses.into_iter().enumerate() {
                updater.update_action_with(index, |mut a| {
                    a.set_output_user_address(address);
                    Ok(())
                })?;
            }
            Ok(())
        })
        .unwrap();
    updater.finish()
}

fn fixture_pczts(value: &Value) -> Vec<Pczt> {
    let envelope = ZcashSignBatch::try_from(bytes(value, "requestCborHex")).unwrap();
    BatchSignRequest::parse(envelope.get_data())
        .unwrap()
        .pczts()
        .to_vec()
}

fn pool_name(pool: ValuePool) -> &'static str {
    match pool {
        ValuePool::Orchard => "orchard",
        ValuePool::Ironwood => "ironwood",
    }
}

fn signature_locations(pczts: &[Pczt]) -> Vec<Value> {
    pczts.iter().enumerate().flat_map(|(pczt_index, pczt)| {
        [("orchard", pczt.orchard()), ("ironwood", pczt.ironwood())].into_iter().flat_map(move |(pool, bundle)| {
            (0..bundle.actions().len()).map(move |action_index| json!({"pcztIndex":pczt_index,"valuePool":pool,"actionIndex":action_index}))
        })
    }).collect()
}

