#[test]
fn account_request_review_sign_response_round_trip() {
    let _scanner = SCANNER_TEST.lock().unwrap();
    let value = fixture();
    let request_parts = parts(&value, "requestUrParts");
    assert!(request_parts.len() > 1);
    reset_vizor_scan();
    assert!(receive_vizor_ur_part("ur:zcash-sign-batch/1-2/not-bytewords".to_owned()).is_err());
    assert!(
        !receive_vizor_ur_part(request_parts[0].clone())
            .unwrap()
            .complete
    );
    reset_vizor_scan(); // Cancelling a scan must discard the partial decoder.
    let mut assembled = None;
    for part in request_parts.iter().rev() {
        let progress = receive_vizor_ur_part(part.clone()).unwrap();
        if progress.complete {
            assembled = progress.cbor;
            break;
        }
        assert!(
            !receive_vizor_ur_part(part.clone()).unwrap().complete,
            "a duplicate must not complete an unfinished request"
        );
    }
    let cbor = assembled.expect("out-of-order UR assembly completed");
    assert_eq!(cbor, bytes(&value, "requestCborHex"));
    let review = inspect_vizor_batch(cbor.clone()).unwrap();
    assert_eq!(
        u64::from(review.transaction_count),
        value["expected"]["transactionCount"].as_u64().unwrap()
    );
    assert_eq!(
        u64::from(review.orchard_spend_count),
        value["expected"]["orchardSpendCount"].as_u64().unwrap()
    );
    assert_eq!(
        u64::from(review.ironwood_spend_count),
        value["expected"]["ironwoodSpendCount"].as_u64().unwrap()
    );
    assert_eq!(
        review.visible_output_total_zat,
        value["expected"]["visibleOutputTotalZat"].as_u64().unwrap()
    );
    assert_eq!(
        serde_json::to_value(review.outputs).unwrap(),
        value["expected"]["outputs"]
    );
    assert_eq!(
        review.request_digest,
        value["expected"]["requestDigest"].as_str().unwrap()
    );
    let signed = sign_vizor_batch(cbor, bytes(&value, "seedHex"), 0).unwrap();
    assert_eq!(
        signed.request_id_hex,
        value["requestIdHex"].as_str().unwrap()
    );
    assert_eq!(
        u64::from(signed.signature_count),
        value["expected"]["signatureCount"].as_u64().unwrap()
    );
    let account =
        export_testnet_account(bytes(&value, "seedHex"), 0, ACCOUNT_NAME.to_owned()).unwrap();
    verify_response(&value, &account, &signed.ur_parts).unwrap();
    reset_vizor_scan();
}

#[test]
fn compact_request_without_fvks_preserves_verified_signatures() {
    let value = fixture();
    let original_cbor = bytes(&value, "requestCborHex");
    let compact_pczts = fixture_pczts(&value)
        .into_iter()
        .map(|pczt| {
            let sighash = Signer::new(pczt.clone()).unwrap().shielded_sighash();
            let compact = Redactor::new(pczt)
                .redact_orchard_with(|mut bundle| {
                    bundle.redact_actions(|mut action| action.clear_spend_fvk());
                    bundle.compact_resolvable_fields();
                })
                .redact_ironwood_with(|mut bundle| {
                    bundle.redact_actions(|mut action| action.clear_spend_fvk());
                    bundle.compact_resolvable_fields();
                })
                .finish();
            Verifier::new(compact.clone())
                .with_orchard::<(), _>(|bundle| {
                    assert!(bundle.actions().iter().all(|a| a.spend().fvk().is_none()));
                    Ok(())
                })
                .unwrap()
                .with_ironwood::<(), _>(|bundle| {
                    assert!(bundle.actions().iter().all(|a| a.spend().fvk().is_none()));
                    Ok(())
                })
                .unwrap();
            assert_eq!(
                Signer::new(compact.clone()).unwrap().shielded_sighash(),
                sighash
            );
            compact
        })
        .collect();
    let cbor: Vec<u8> = ZcashSignBatch::new(
        REQUEST_ID.to_vec(),
        BatchSignRequest::new(compact_pczts).serialize().unwrap(),
    )
    .try_into()
    .unwrap();
    assert!(cbor.len() < original_cbor.len());
    let review = inspect_vizor_batch(cbor.clone()).unwrap();
    assert_eq!(
        review.outputs,
        inspect_vizor_batch(original_cbor).unwrap().outputs
    );
    let signed = sign_vizor_batch(cbor, bytes(&value, "seedHex"), 0).unwrap();
    verify_response(&value, &parts(&value, "accountUrParts"), &signed.ur_parts).unwrap();
}

