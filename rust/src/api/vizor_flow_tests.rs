fn bytes(value: &Value, field: &str) -> Vec<u8> {
    hex::decode(value[field].as_str().expect(field)).expect("fixture hex")
}

fn parts(value: &Value, field: &str) -> Vec<String> {
    value[field]
        .as_array()
        .expect(field)
        .iter()
        .map(|part| part.as_str().expect("UR string").to_owned())
        .collect()
}

fn decode_ur(parts: &[String], expected_type: &str) -> Result<Vec<u8>, String> {
    if parts.is_empty() {
        return Err("UR response has no parts".to_owned());
    }
    let prefix = format!("ur:{expected_type}/");
    let mut decoder = ur::Decoder::default();
    for part in parts {
        let normalized = part.to_lowercase();
        if !normalized.starts_with(&prefix) {
            return Err("unexpected UR type".to_owned());
        }
        let (kind, payload) = ur::decode(&normalized).map_err(|e| e.to_string())?;
        if kind == ur::ur::Kind::SinglePart {
            if parts.len() != 1 {
                return Err("mixed single/multipart UR".to_owned());
            }
            return Ok(payload);
        }
        decoder.receive(&normalized).map_err(|e| e.to_string())?;
    }
    decoder
        .message()
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "incomplete UR response".to_owned())
}

fn encode_request(cbor: &[u8]) -> Vec<String> {
    encode_ur(cbor, "zcash-sign-batch")
}

fn encode_ur(cbor: &[u8], ur_type: &str) -> Vec<String> {
    let mut encoder = ur::Encoder::new(cbor, 120, ur_type).unwrap();
    (0..encoder.fragment_count())
        .map(|_| encoder.next_part().unwrap().to_uppercase())
        .collect()
}

